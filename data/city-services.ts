export function getCityServiceData(
  cityId: CityId,
  serviceId: string
): CityServiceData | undefined {
  return cityServiceData[key(cityId, serviceId)];
}

export function getCityServiceCombinations(): { cityId: CityId; serviceId: string }[] {
  const result: { cityId: CityId; serviceId: string }[] = [];
  for (const k of Object.keys(cityServiceData)) {
    const [cityId, serviceId] = k.split(':');
    result.push({ cityId: cityId as CityId, serviceId });
  }
  return result;
}
