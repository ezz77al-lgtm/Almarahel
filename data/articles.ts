export function getArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

export function getArticlesByCategory(categoryId: string): Article[] {
  return articles.filter((a) => a.categoryId === categoryId);
}

export function getLatestArticles(limit: number = 4): Article[] {
  return [...articles]
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())
    .slice(0, limit);
}

export function getRelatedArticles(article: Article, limit: number = 3): Article[] {
  return articles
    .filter(
      (a) =>
        a.id !== article.id &&
        (a.categoryId === article.categoryId ||
          a.relatedServiceIds.some((id) => article.relatedServiceIds.includes(id)))
    )
    .slice(0, limit);
}
